"""Build an offline Apple Silicon app; the Ed submission still includes source.

Build dependency: PyInstaller 6.22.3. Keep build tools in
.submission-build/builder-packages so the application requirements stay small.
"""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory
from zipfile import ZipFile


START_HERE = """ANCHOR - OFFLINE MACOS APP

This build contains Python, PySide6, Shiboken and the required Qt libraries.
No Python or pip installation is needed to run this app on Apple Silicon macOS.
It is not a Windows, Linux or Intel-only Mac executable.

1. Extract the complete ZIP. Keep Anchor.app intact.
2. Double-click Anchor.app for a fresh personal profile.
3. For disposable presentation examples, double-click Open Preview.command.
   Preview edits are discarded when the window closes.

Normal app data is stored in:
  ~/Library/Application Support/Anchor/
The source version uses data/ beside app.py instead. Back up the complete
profile folder, including imported images, when transferring your own data.

This student build is ad-hoc signed, not Apple-notarised. After downloading,
macOS may require the standard Open Anyway approval in Privacy & Security.
Approve only the copy you obtained from the student's declared download link.

Music is optional and requires Spotify/Apple Music already installed plus
explicit Connect and macOS Automation permission. The planning application
and its built-in scenery do not require those players or a network connection.

The source code is supplied separately to Ed. Third-party components and build
details are documented alongside this file. This build has been checked on the
author's Mac; do not describe other operating systems as independently tested.
"""


def make_spec(root):
    data = [(str(path), "assets") for path in sorted((root / "assets").glob("*.txt"))]
    return f'''# Generated by tools/build_macos_app.py; no personal saves included.
a = Analysis([{str(root / "app.py")!r}], pathex=[{str(root)!r}],
             binaries=[], datas={data!r}, hiddenimports=[], hookspath=[],
             hooksconfig={{}}, runtime_hooks=[], excludes=[], noarchive=False,
             optimize=0)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='Anchor',
          debug=False, bootloader_ignore_signals=False, strip=False, upx=False,
          console=False, argv_emulation=False, target_arch='arm64',
          codesign_identity=None, entitlements_file=None)
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name='Anchor')
app = BUNDLE(coll, name='Anchor.app', icon=None,
             bundle_identifier='org.comp9001.anchor',
             info_plist={{'CFBundleShortVersionString': '1.1.2',
                          'CFBundleVersion': '4',
                          'NSHighResolutionCapable': True,
                          'NSAppleEventsUsageDescription':
                          'Anchor controls your selected music player only after you press Connect or a playback control.'}})
'''


def build(root, package_only=False):
    if sys.platform != "darwin" or platform.machine() != "arm64":
        raise RuntimeError("Build this executable on an Apple Silicon Mac.")
    build_root = root / ".submission-build"
    tools = build_root / "builder-packages"
    env = dict(os.environ)
    env["PYTHONPATH"] = str(tools) + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    env["PYINSTALLER_CONFIG_DIR"] = str(build_root / "pyinstaller-cache")
    if not package_only:
        spec_folder = build_root / "spec"
        spec_folder.mkdir(parents=True, exist_ok=True)
        spec = spec_folder / "Anchor.spec"
        spec.write_text(make_spec(root), encoding="utf-8")
        subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm",
                        "--distpath", str(build_root / "dist"),
                        "--workpath", str(build_root / "work"), str(spec)],
                       cwd=root, env=env, check=True)

    built_app = build_root / "dist" / "Anchor.app"
    if not built_app.is_dir():
        raise FileNotFoundError("Build Anchor.app before packaging it.")
    external = root / "submission" / "04_External_Files"
    staging = external / "Anchor-macOS-AppleSilicon"
    staging.mkdir(parents=True, exist_ok=True)
    target_app = staging / "Anchor.app"
    if target_app.exists():
        shutil.rmtree(target_app)
    shutil.copytree(built_app, target_app, symlinks=True)
    (staging / "START_HERE.txt").write_text(START_HERE, encoding="utf-8")
    launcher = staging / "Open Preview.command"
    launcher.write_text('#!/bin/bash\nset -e\ncd "$(dirname "$0")"\nexec ./Anchor.app/Contents/MacOS/Anchor --preview\n', encoding="utf-8")
    launcher.chmod(0o755)
    notices = staging / "THIRD_PARTY_NOTICES"
    notices.mkdir(exist_ok=True)
    python_license = build_root / "third-party-notices" / "CPython" / "LICENSE.txt"
    if python_license.is_file():
        shutil.copy2(python_license, notices / "PYTHON_LICENSE.txt")
    else:
        raise FileNotFoundError("Supply CPython's upstream licence in .submission-build/third-party-notices/CPython/ before packaging.")
    for name in ("PyInstaller", "altgraph", "macholib", "packaging"):
        for folder in tools.glob(name.lower() + "*.dist-info"):
            for path in folder.rglob("*"):
                if path.is_file() and ("license" in path.name.lower() or "copying" in path.name.lower()):
                    shutil.copy2(path, notices / (name + "_" + path.name))
    # The offline-source preparation may supply upstream Qt licence texts.
    qt_notices = external / "Anchor-Offline-Source" / "THIRD_PARTY_NOTICES"
    if qt_notices.is_dir():
        shutil.copytree(qt_notices, notices / "QT_SOURCE_NOTICES", dirs_exist_ok=True)
    upstream_notices = build_root / "third-party-notices"
    if upstream_notices.is_dir():
        shutil.copytree(upstream_notices, notices / "QT_UPSTREAM_LICENSES", dirs_exist_ok=True)
    (notices / "COMPONENTS.txt").write_text(
        "Python 3.12.12; PySide6-Essentials 6.8.3; Shiboken6 6.8.3; Qt 6.8.3.\n"
        "Build tool: PyInstaller 6.22.3 (GPL with bootloader exception).\n"
        "Qt/PySide source and licensing: https://code.qt.io/cgit/pyside/pyside-setup.git/tree/?h=6.8.3\n"
        "Qt libraries are dynamically linked and kept as separate bundled files.\n"
        "Build documentation: https://pyinstaller.org/en/stable/usage.html\n",
        encoding="utf-8")
    metadata = {
        "built_at_utc": datetime.now(timezone.utc).isoformat(),
        "system": platform.system(), "architecture": platform.machine(),
        "tested_host_macos": platform.mac_ver()[0],
        "python": platform.python_version(), "gui_dependency": "PySide6-Essentials==6.8.3",
        "pyinstaller": "6.22.3", "notarised": False,
        "runtime_is_self_contained": True,
        "other_platforms_tested": False,
        "personal_saves_included": False,
    }
    (staging / "BUILD_INFO.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    archive = external / "Anchor-macOS-AppleSilicon.zip"
    temporary = build_root / "Anchor-macOS-AppleSilicon.zip"
    if temporary.exists():
        temporary.unlink()
    # Cloud-synchronised Desktop folders may recreate FinderInfo immediately
    # after removal. Sign a clean temporary copy outside that file provider.
    with TemporaryDirectory(prefix="anchor-signed-release-") as folder:
        clean = Path(folder) / staging.name
        subprocess.run(["/usr/bin/ditto", "--norsrc", "--noextattr", str(staging), str(clean)], check=True)
        clean_app = clean / "Anchor.app"
        subprocess.run(["/usr/bin/chflags", "-R", "nohidden", str(clean_app)], check=True)
        subprocess.run(["/usr/bin/xattr", "-cr", str(clean_app)], check=True)
        subprocess.run(["/usr/bin/codesign", "--force", "--deep", "--sign", "-",
                        "--timestamp=none", str(clean_app)], check=True)
        subprocess.run(["/usr/bin/codesign", "--verify", "--deep", "--strict", str(clean_app)], check=True)
        subprocess.run(["/usr/bin/ditto", "-c", "-k", "--norsrc", "--noextattr", "--keepParent",
                        str(clean), str(temporary)], check=True)
    with ZipFile(temporary) as packaged:
        if packaged.testzip() is not None:
            raise RuntimeError("The macOS app ZIP failed its CRC check.")
        if any("data/planner.json" in name or "/.venv/" in name for name in packaged.namelist()):
            raise RuntimeError("Unexpected private or virtual-environment file in the runtime.")
    temporary.replace(archive)
    shutil.rmtree(staging)
    print(json.dumps({"archive": str(archive), "bytes": archive.stat().st_size,
                      "platform": "macOS Apple Silicon arm64"}, indent=2))


def main():
    parser = argparse.ArgumentParser(description="Build Anchor's offline Apple Silicon macOS app.")
    parser.add_argument("--package-only", action="store_true", help="Reuse the existing app build.")
    options = parser.parse_args()
    build(Path(__file__).resolve().parents[1], options.package_only)


if __name__ == "__main__":
    main()
